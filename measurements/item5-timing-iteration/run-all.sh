#!/usr/bin/env bash
# Bounded timing iteration for T1 item 5 (issue #161), evidence-only.
#
# Produces, in a scratch tree laid out like this repo, under
# measurements/item5-timing-iteration/:
#
#   reports/v0/sta-lef-only.report.json        control: the committed stream
#                                               re-measured on THIS host's
#                                               engine (15 corners, LEF-only)
#   reports/vN/{synth.json,par.json,           one dir per variant (issue #161
#     sta-lef-only.report.json}                step 2): synth where the variant
#                                               re-synthesizes, the P&R record,
#                                               the graded 15-corner LEF-only
#                                               STA over that variant's routed
#                                               DEF
#   work/vN/*                                  scratch artifacts (netlist,
#                                               routed DEF/GDS, klt engine
#                                               logs) -- never committed
#   requests/sta-<v>-spef.request.json         generated by the `spef` phase
#   reports/<v>/{extract.report.json,          best-variant SPEF phase
#     logic_tile_routed.spef, sta-spef.report.json}
#
# Variants (each one change from its named base; every graded STA request is
# byte-identical to measurements/item5-24um/sta-lef-only.request.json except
# for the def/library it points at -- the pre-registered constraint set: 20 ns
# on clk, I/O delays 0, ideal clock, all 15 corners of the variant's library):
#
#   v0  control: committed DEF, committed constraint set, this host's engine
#   v1  synthesis mapped at ss_125C_1v62 with clock_period_ns 20 (ABC -D);
#       P&R as committed (tt_025C_5v00)
#   v2  committed netlist; P&R pdk.corner -> ss_125C_1v62
#   v3  v1's netlist AND P&R at ss_125C_1v62
#   v4  v2 + constraints.input/output_delay_ns 0 in the P&R request, so
#       in-flow repair_timing sees the output_setup paths that fail
#   v5  v3 + the same I/O delays
#   v6  the 9-track library gf180mcu_fd_sc_mcu9t5v0, otherwise the committed
#       flow (tt, period null in synthesis; tt P&R; same core 106.4 x 105.84
#       um = 190 x 21 sites of 0.56 x 5.04 um; tapcell 24 um)
#
# Nothing here touches the committed tile: no file under layout/, flow/ or
# rtl/ is written, no false_path_from / period change / corner removal is
# applied to any graded run, and the klt pin (flow/pdk.json,
# klayout-tools==0.9.0) is forced via flow/klt.sh (uvx) or a throwaway venv.
#
# Usage (from anywhere in the repo checkout):
#   measurements/item5-timing-iteration/run-all.sh TREE PHASE [ARG]
#     TREE  scratch tree to build (safely re-created each invocation)
#     PHASE control | variant V1..V6 | spef VN | summary
set -euo pipefail

src_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(git -C "$src_here" rev-parse --show-toplevel)"
TREE="${1:?usage: run-all.sh TREE PHASE [ARG]}"
PHASE="${2:?usage: run-all.sh TREE PHASE [ARG]}"
ARG="${3:-}"

# --- pinned klt + PDK, resolved in the source checkout ------------------------
source "$repo/flow/klt.sh" || exit 2
source "$repo/flow/pdk-root.sh" || exit 2
PDK_ROOT="$(pdk_root_resolve)" || exit 2
export PDK_ROOT
export PDK="${PDK:-$(jq -er .smoke_variant "$repo/flow/pdk.json")}"
"$repo/flow/setup-pdk.sh" --verify || exit 2

here_rel="measurements/item5-timing-iteration"
req_rel="$here_rel/requests"

# --- scratch tree: this repo's shape, git-init so klt records repo-relative
# paths exactly like the committed records do (the run-synth.sh discipline).
# rtl is a symlink so the vendored sources stay byte-identical to the pin.
# Built once; later invocations refresh only the request documents, so
# work/ (a variant's netlist feeding a later variant's P&R) survives. --------
if [[ ! -d "$TREE/.git" ]]; then
  rm -rf "$TREE"
  mkdir -p "$TREE"/{flow/tile/netlist,layout,"$here_rel"}
  cd "$TREE"
  git init -q .
  git config user.email run-all@example.invalid
  git config user.name run-all
  ln -s "$repo/rtl" rtl
  cp "$repo/layout/logic_tile_routed.def" layout/
  cp "$repo/flow/tile/netlist/logic_tile_routed_synth.v" flow/tile/netlist/
  mkdir -p "$here_rel/reports" "$here_rel/work"
fi
cd "$TREE"
# overlay the committed request documents over the tree's requests/ (never
# delete: phases generate extra requests there, e.g. sta-<v>-spef)
mkdir -p "$here_rel/requests"
cp -r "$src_here/requests/." "$here_rel/requests/"
# the anatomy phase reads the committed item5-24um SPEF + request template
rm -rf measurements/item5-24um
cp -r "$repo/measurements/item5-24um" measurements/
git add -A >/dev/null

sta_flags=(--pdk gf180mcuD --pdk-root "$PDK_ROOT" --format json)
rel_root="$here_rel"

stamp() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }
say() { echo "[$(stamp)] $*"; }

keep_klt() {  # keep_klt NAME STEP -- preserve klt's engine logs under work/
  local name="$1" step="$2"
  if [[ -d "$here_rel/requests/.klt" ]]; then
    mkdir -p "$rel_root/work/$name/klt/$step"
    chmod -R u+w "$rel_root/work/$name/klt/$step" 2>/dev/null || true
    cp -r "$here_rel/requests/.klt/." "$rel_root/work/$name/klt/$step/"
    chmod -R u+w "$rel_root/work/$name/klt/$step"
    rm -rf "$here_rel/requests/.klt"
  fi
}

pdk_root="$(cd "$PDK_ROOT" && pwd)"
fixup() {  # committed-record discipline (run-par.sh): repo-relative paths,
  # symbolic $PDK_ROOT -- deterministic rewrite of the run's own outputs
  sed -i -e "s#$TREE/##g" -e "s#$pdk_root#\\\$PDK_ROOT#g" "$1"
}

run_sta() {  # run_sta NAME REQUEST
  local name="$1" request="$2"
  say "sta $name"
  mkdir -p "$rel_root/reports/$name"
  klt sta "$request" "${sta_flags[@]}" > "$rel_root/reports/$name/sta-lef-only.report.json"
  jq -er '.status' "$rel_root/reports/$name/sta-lef-only.report.json" >/dev/null
  fixup "$rel_root/reports/$name/sta-lef-only.report.json"
  keep_klt "$name" sta
}

run_synth() {  # run_synth NAME REQUEST -> netlist at work/NAME/…_synth.v
  local name="$1" request="$2"
  say "synthesize $name"
  mkdir -p "$rel_root/reports/$name" "$rel_root/work/$name"
  klt synthesize --format json "$request" > "$rel_root/reports/$name/synth.json"
  fixup "$rel_root/reports/$name/synth.json"
  local net
  net="$(ls -t "$here_rel"/requests/.klt/synthesize/run-*/logic_tile_routed_synth.v | head -n1)"
  cp "$net" "$rel_root/work/$name/logic_tile_routed_synth.v"
  keep_klt "$name" synthesize
}

run_par() {  # run_par NAME REQUEST -> routed DEF/GDS at work/NAME/
  local name="$1" request="$2"
  say "place-and-route $name"
  mkdir -p "$rel_root/reports/$name" "$rel_root/work/$name"
  klt place-and-route --format json "$request" > "$rel_root/reports/$name/par.json"
  fixup "$rel_root/reports/$name/par.json"
  local out="$here_rel/requests/.klt/place-and-route"
  cp "$out/logic_tile_routed.def" "$rel_root/work/$name/logic_tile_routed.def"
  cp "$out/logic_tile_routed.gds" "$rel_root/work/$name/logic_tile_routed.gds"
  cp "$out/logic_tile_routed.v"   "$rel_root/work/$name/logic_tile_routed.v" 2>/dev/null || true
  keep_klt "$name" place-and-route
}

case "$PHASE" in
  control)
    run_sta v0 "$req_rel/sta-v0.request.json"
    ;;
  anatomy)
    # single-corner diagnostic on the committed stream (issue #161 step 1):
    # ss_125C_1v62 with the committed item5-24um SPEF, so klt's own
    # report_checks blocks (the pre/post read_spef delay fingerprints) print
    # the worst setup path stage by stage into the engine stdout, which is
    # preserved under work/anatomy/klt/sta/
    python3 - <<'PY'
import json
from pathlib import Path
req = json.loads(Path("measurements/item5-24um/sta-spef.request.json").read_text())
req["pdk"]["corners"] = ["ss_125C_1v62"]
req["def"] = "../../../layout/logic_tile_routed.def"
req["spef"] = "../../../measurements/item5-24um/logic_tile_routed.spef"
out = Path("measurements/item5-timing-iteration/requests/sta-anatomy.request.json")
out.write_text(json.dumps(req, indent=2) + "\n")
print(f"anatomy request: {out}")
PY
    run_sta anatomy "$req_rel/sta-anatomy.request.json"
    # transcribe klt's own report_checks worst-setup blocks (pre- and
    # post-read_spef) from the preserved engine stdout, verbatim
    so="$(find "$rel_root/work/anatomy/klt" -path '*openroad-logs/*/stdout.log' | head -n1)"
    awk '/KLT_STA_DELAY_PRE_BEGIN/,/KLT_STA_DELAY_PRE_END/{print}' "$so" \
      > "$rel_root/reports/anatomy/worst-setup-path-ss125-lef.txt"
    awk '/KLT_STA_DELAY_POST_BEGIN/,/KLT_STA_DELAY_POST_END/{print}' "$so" \
      > "$rel_root/reports/anatomy/worst-setup-path-ss125-spef.txt"
    echo "anatomy blocks: $(grep -c 'Startpoint:' "$rel_root/reports/anatomy/worst-setup-path-ss125-spef.txt") paths (spef)"
    ;;
  variant)
    case "$ARG" in
      v1) run_synth v1 "$req_rel/synth-v1.request.json"
          run_par  v1 "$req_rel/par-v1.request.json"
          run_sta  v1 "$req_rel/sta-v1.request.json" ;;
      v2) run_par v2 "$req_rel/par-v2.request.json"
          run_sta v2 "$req_rel/sta-v2.request.json" ;;
      v3) run_par v3 "$req_rel/par-v3.request.json"
          run_sta v3 "$req_rel/sta-v3.request.json" ;;
      v4) run_par v4 "$req_rel/par-v4.request.json"
          run_sta v4 "$req_rel/sta-v4.request.json" ;;
      v5) run_par v5 "$req_rel/par-v5.request.json"
          run_sta v5 "$req_rel/sta-v5.request.json" ;;
      v6) run_synth v6 "$req_rel/synth-v6.request.json"
          run_par  v6 "$req_rel/par-v6.request.json"
          run_sta  v6 "$req_rel/sta-v6.request.json" ;;
      *) echo "::error::unknown variant $ARG" >&2; exit 2 ;;
    esac
    ;;
  spef)  # run-all.sh TREE spef VN -- extract + SPEF STA on variant VN's stream
    [[ "$ARG" =~ ^v[0-9]+$ ]] || { echo "::error::spef needs a variant name" >&2; exit 2; }
    say "extract $ARG"
    scratch_sp="$(mktemp -d)/logic_tile_routed.sp"
    klt extract "$rel_root/work/$ARG/logic_tile_routed.gds" \
      --deck gf180mcu --pdk gf180mcuD --pdk-root "$PDK_ROOT" \
      --parasitics --spef "$rel_root/work/$ARG/logic_tile_routed.spef" \
      --def-net-names --def-net-connections "$rel_root/work/$ARG/logic_tile_routed.def" \
      -o "$scratch_sp" --format json > "$rel_root/reports/$ARG/extract.report.json"
    rm -rf "$(dirname "$scratch_sp")"
    fixup "$rel_root/reports/$ARG/extract.report.json"
    keep_klt "$ARG" extract
    python3 - "$ARG" <<'PY'
import json, sys
from pathlib import Path
v = sys.argv[1]
here = Path("measurements/item5-timing-iteration")
req = json.loads((here / f"requests/sta-{v}.request.json").read_text())
req["spef"] = f"../work/{v}/logic_tile_routed.spef"
out = here / f"requests/sta-{v}-spef.request.json"
out.write_text(json.dumps(req, indent=2) + "\n")
print(f"spef request: {out}")
PY
    say "sta $ARG spef"
    klt sta "$req_rel/sta-$ARG-spef.request.json" "${sta_flags[@]}" \
      > "$rel_root/reports/$ARG/sta-spef.report.json"
    fixup "$rel_root/reports/$ARG/sta-spef.report.json"
    keep_klt "$ARG" sta-spef
    ;;
  summary)
    python3 - <<'PY'
import json
from pathlib import Path
root = Path("measurements/item5-timing-iteration/reports")
for d in sorted(p for p in root.iterdir() if p.is_dir()):
    row = {"variant": d.name}
    par = d / "par.json"
    if par.exists():
        p = json.loads(par.read_text())
        row.update(core_area_um2=p.get("core_area_um2"),
                   utilization_pct=p.get("utilization_pct"),
                   route_drc=p.get("route_drc_violation_count"))
    sy = d / "synth.json"
    if sy.exists():
        s = json.loads(sy.read_text())
        row.update(cell_area_um2=s.get("area_um2"), cells=s.get("instance_count"))
    for sta_name, fname in (("lef", "sta-lef-only.report.json"),
                            ("spef", "sta-spef.report.json")):
        f = d / fname
        if not f.exists():
            continue
        corners = json.loads(f.read_text())["corners"]
        worst = min(corners, key=lambda c: c["worst_slack_ns"])
        row[sta_name] = {
            "worst_corner": worst["corner"],
            "wns_ns": worst["worst_slack_ns"],
            "tns_worst_corner_ns": worst.get("total_negative_slack_ns"),
            "setup_violations_total": sum(c["setup_violation_count"] for c in corners),
            "failing_corners": sum(1 for c in corners if c["setup_violation_count"] > 0),
            "worst_hold_ns": min(c["worst_hold_slack_ns"] for c in corners),
        }
    print(json.dumps(row))
PY
    ;;
  *) echo "::error::unknown phase $PHASE" >&2; exit 2 ;;
esac
say "phase $PHASE $ARG done"
