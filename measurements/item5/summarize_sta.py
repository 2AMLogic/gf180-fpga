#!/usr/bin/env python3
"""Render (or check) the T1 item-5 per-corner worst setup path table.

    python3 -I measurements/item5/summarize_sta.py            # write setup-paths.md
    python3 -I measurements/item5/summarize_sta.py --check     # fail if stale

Reads the two committed STA reports (LEF-only and SPEF) and transcribes, for
every corner in each, the recorded `worst_setup_path` alongside the corner's
aggregate slack and violation counts. It records what the reports say; it
draws no conclusion about whether the reported path should be timed,
constrained or excluded.

Numeric cells are emitted exactly as the reports serialize them (`json.dumps`
of the parsed value round-trips every field this script emits), so
`worst_slack_ns` and `worst_setup_path.slack_ns` keep their own precision and
are never re-rounded or reconciled against each other.

Standard library only; no PDK, no OpenROAD, no re-run.
"""
import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = HERE / "setup-paths.md"

# (label, report filename) -- rendered in this order.
RUNS = (
    ("LEF-only", "sta-lef-only.report.json"),
    ("SPEF", "sta-spef.report.json"),
)

ABSENT = "(absent)"


def num(value):
    """Render a numeric report field exactly as the report serializes it."""
    if value is None:
        return ABSENT
    return f"`{json.dumps(value)}`"


def name(value):
    """Render a textual report field, or a visible marker when absent."""
    return ABSENT if value is None else f"`{value}`"


def distinct(values):
    """'N distinct: `a`, `b`' over values in first-seen order."""
    seen = []
    for v in values:
        if v not in seen:
            seen.append(v)
    rendered = ", ".join(name(v) for v in seen)
    return len(seen), rendered


def path_cells(path):
    """check_type / start point / end point cells, or a visible marker."""
    status = path.get("status")
    if status == "ok":
        return [name(path.get(k)) for k in ("check_type", "startpoint", "endpoint")]
    marker = f"(status: `{status}`)" if status is not None else "(no `worst_setup_path`)"
    return [marker, marker, marker]


def render():
    runs = []
    for label, filename in RUNS:
        data = (HERE / filename).read_bytes()
        runs.append({
            "label": label,
            "path": (HERE / filename).relative_to(ROOT).as_posix(),
            "sha256": hashlib.sha256(data).hexdigest(),
            "corners": json.loads(data)["corners"],
        })

    rows = [(r, c) for r in runs for c in r["corners"]]
    paths = [c.get("worst_setup_path") or {} for _, c in rows]
    ok = [p for p in paths if p.get("status") == "ok"]

    n_check, s_check = distinct(p.get("check_type") for p in ok)
    n_start, s_start = distinct(p.get("startpoint") for p in ok)

    lines = [
        "# T1 item 5 -- per-corner worst setup path",
        "",
        "Generated by `measurements/item5/summarize_sta.py` from the two committed",
        "STA reports; do not edit by hand.",
        "",
        "```sh",
        "python3 -I measurements/item5/summarize_sta.py           # re-render",
        "python3 -I measurements/item5/summarize_sta.py --check    # fail if stale",
        "```",
        "",
        "This file transcribes what the reports record. It draws no conclusion about",
        "whether the reported path should be timed, constrained or excluded.",
        "",
        "## Provenance",
        "",
        "Rendered from these committed reports, by sha256 of the file bytes:",
        "",
        "| run | report | sha256 |",
        "|---|---|---|",
    ]
    for r in runs:
        lines.append(f"| {r['label']} | `{r['path']}` | `{r['sha256']}` |")

    lines += [
        "",
        f"{len(rows)} rows below: {' + '.join(str(len(r['corners'])) for r in runs)}"
        f" corners across {len(runs)} runs.",
        "",
        "## What the reports record",
        "",
        f"- **Check type**: {n_check} distinct `worst_setup_path.check_type`"
        f" across the {len(ok)} rows recording `status: ok` -- {s_check}.",
        f"- **Start point**: {n_start} distinct `worst_setup_path.startpoint`"
        f" across the same {len(ok)} rows -- {s_start}.",
    ]

    # Endpoints are a per-run property in the committed data, so they are counted
    # per run as well as overall -- an unqualified total would read as if every
    # row shared one endpoint.
    per_run = []
    for r in runs:
        r_ok = [
            c["worst_setup_path"] for c in r["corners"]
            if (c.get("worst_setup_path") or {}).get("status") == "ok"
        ]
        n, s = distinct(p.get("endpoint") for p in r_ok)
        per_run.append(f"{n} in the {r['label']} run ({s})")
    n_end, s_end = distinct(p.get("endpoint") for p in ok)
    lines.append(
        f"- **End point**: {' and '.join(per_run)};"
        f" {n_end} distinct across both runs -- {s_end}."
    )

    n_ok = len(ok)
    n_consistent = sum(1 for p in paths if p.get("consistent_with_aggregate") is True)
    lines += [
        f"- **Status**: {n_ok} of {len(rows)} rows record"
        f" `worst_setup_path.status: ok`; {n_consistent} of {len(rows)} record"
        " `consistent_with_aggregate: true`.",
        "",
        "## Per-corner worst setup path",
        "",
        "`worst_slack_ns`, `setup_violation_count` and `worst_hold_slack_ns` are the",
        "corner-level aggregates; the remaining columns come from that corner's",
        "`worst_setup_path`. Values appear as the reports serialize them.",
        "",
        "| corner | run | worst_slack_ns | setup_violation_count |"
        " check_type | start point | end point | worst_hold_slack_ns |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r, c in rows:
        check, start, end = path_cells(c.get("worst_setup_path") or {})
        lines.append(
            f"| `{c['corner']}` | {r['label']} | {num(c.get('worst_slack_ns'))} |"
            f" {num(c.get('setup_violation_count'))} | {check} | {start} | {end} |"
            f" {num(c.get('worst_hold_slack_ns'))} |"
        )

    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(
        description="Render measurements/item5/setup-paths.md from the committed STA reports."
    )
    ap.add_argument(
        "--check", action="store_true",
        help="compare the committed file with a fresh render; exit non-zero if they differ",
    )
    args = ap.parse_args(argv)

    text = render()
    rel = OUT.relative_to(ROOT).as_posix()

    if args.check:
        if not OUT.is_file():
            print(f"ERROR: {rel} is missing; run measurements/item5/summarize_sta.py",
                  file=sys.stderr)
            return 1
        committed = OUT.read_text()
        if committed != text:
            diff = difflib.unified_diff(
                committed.splitlines(keepends=True), text.splitlines(keepends=True),
                fromfile=f"{rel} (committed)", tofile=f"{rel} (fresh render)",
            )
            sys.stderr.writelines(diff)
            print(f"ERROR: {rel} has drifted from the reports;"
                  " run measurements/item5/summarize_sta.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date")
        return 0

    OUT.write_text(text)
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
