#!/usr/bin/env python3
"""Render (or check) the cost-per-LUT4 estimate for the routed gf180mcu tile.

    python3 -I measurements/cost_per_lut.py            # write cost-per-lut.md
    python3 -I measurements/cost_per_lut.py --check    # fail if stale

Reads the committed place-and-route record (`layout/records/step0-par.json`)
for the measured tile area, and the committed routed DEF
(`layout/logic_tile_routed.def`) for an independent cross-check of the same
area. The shuttle price, die quantity, slot core area and LUT4 count are kept
below as dated constants cited to their public sources, so the whole
calculation runs offline: nothing is fetched at render time.

The result is an area-proportional shuttle estimate, not a quotation.

Standard library only; no PDK, no OpenROAD, no network access.
"""
import argparse
import difflib
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = HERE / "cost-per-lut.md"

RECORD = ROOT / "layout" / "records" / "step0-par.json"
ROUTED_DEF = ROOT / "layout" / "logic_tile_routed.def"
RECORD_REL = RECORD.relative_to(ROOT).as_posix()
DEF_REL = ROUTED_DEF.relative_to(ROOT).as_posix()

# Cited constants -- update each value together with its citation and date.
N_LUT4 = 4  # rtl/common/rtl/logic_tile_routed.v: the g_slice generate loop instantiates 4 x lut4_slice
PRICE_USD = 8000.0  # slot price; wafer.space GF180MCU Run 3, standard 1x1 slot
DIE_QUANTITY = 1000  # dies bought per slot; same listing
SLOT_CORE_AREA_MM2 = 12.92  # usable area inside the default pad ring, mm^2; same listing
PRICE_SOURCE = "wafer.space GF180MCU Run 3, standard 1×1 slot"
PRICE_URL = "https://wafer.space/price"
PRICE_DATE = "2026-11-19"  # date the listing was retrieved


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_def_outline(path):
    """(width_um, height_um, area_um2) from the DEF UNITS and DIEAREA lines."""
    units = None
    diearea = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if units is None and line.startswith("UNITS DISTANCE MICRONS"):
            units = float(line.split()[3])
        elif diearea is None and line.startswith("DIEAREA"):
            tokens = [t for t in line.replace("(", " ").replace(")", " ").split()[1:] if t != ";"]
            x0, y0, x1, y1 = (int(t) for t in tokens[:4])
            diearea = (x1 - x0, y1 - y0)
        if units is not None and diearea is not None:
            break
    if units is None or diearea is None:
        raise SystemExit(f"ERROR: could not parse UNITS/DIEAREA from {DEF_REL}")
    w_dbu, h_dbu = diearea
    w_um = w_dbu / units
    h_um = h_dbu / units
    return w_dbu, h_dbu, units, w_um, h_um, w_um * h_um


def render():
    record = json.loads(RECORD.read_text(encoding="utf-8"))
    die_area_um2 = record["die_area_um2"]
    core_area_um2 = record["core_area_um2"]

    area_per_lut_um2 = die_area_um2 / N_LUT4
    area_per_lut_mm2 = area_per_lut_um2 / 1e6

    w_dbu, h_dbu, units, w_um, h_um, def_area_um2 = parse_def_outline(ROUTED_DEF)
    def_per_lut_um2 = def_area_um2 / N_LUT4

    per_die_usd = PRICE_USD / DIE_QUANTITY
    price_per_mm2 = per_die_usd / SLOT_CORE_AREA_MM2
    cost_per_lut_usd = price_per_mm2 * area_per_lut_mm2
    cost_per_lut_def_usd = price_per_mm2 * (def_per_lut_um2 / 1e6)

    lines = [
        "# Cost per LUT4 -- routed gf180mcu tile",
        "",
        "Generated by `measurements/cost_per_lut.py` from the committed",
        "place-and-route record and routed DEF; do not edit by hand.",
        "",
        "```sh",
        "python3 -I measurements/cost_per_lut.py            # re-render",
        "python3 -I measurements/cost_per_lut.py --check    # fail if stale",
        "```",
        "",
        "**Headline: the committed routed tile measures"
        f" {area_per_lut_um2:,.1f} µm² of layout per LUT4, and at wafer.space's"
        f" published GF180MCU Run 3 pricing (retrieved {PRICE_DATE}) that is an"
        f" estimated USD {cost_per_lut_usd:.5f} per LUT4 per die. This is an"
        " area-proportional shuttle estimate, not a quotation.**",
        "",
        "## Provenance",
        "",
        "Rendered from these committed files, by sha256 of the file bytes:",
        "",
        "| role | file | sha256 |",
        "|---|---|---|",
        f"| measured tile area | `{RECORD_REL}` | `{sha256(RECORD)}` |",
        f"| routed DEF (independent cross-check) | `{DEF_REL}` | `{sha256(ROUTED_DEF)}` |",
        "",
        "The pricing inputs (slot price, die quantity, slot core area, retrieval",
        "date) and the LUT4 count are constants in the generator, cited to their",
        "public sources; nothing is fetched at render time.",
        "",
        "## Area per LUT4 (measured)",
        "",
        f"`{RECORD_REL}` records `die_area_um2` = {die_area_um2:g} for the routed",
        "tile -- the full routed outline, so each LUT4 carries its share of the",
        "local routing, the switch matrix, the supply rails and the tile margins.",
        f"(The separate `core_area_um2` = {core_area_um2:g} measures the tile",
        "interior; the estimate uses the full outline.) The routed RTL",
        "instantiates four `lut4_slice` BELs -- the `g_slice` generate loop in",
        "`rtl/common/rtl/logic_tile_routed.v` -- so:",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| routed tile die area | {die_area_um2:,.1f} µm² |",
        f"| LUT4 slices in the routed RTL | {N_LUT4} |",
        f"| **area per LUT4** | **{area_per_lut_um2:,.1f} µm²** = {area_per_lut_mm2:.7f} mm² |",
        "",
        "Cross-check against the routed DEF: its outline is"
        f" {w_dbu:,} × {h_dbu:,} database units at {units:,.0f} database units/µm,",
        f"i.e. {w_um:.2f} µm × {h_um:.2f} µm = {def_area_um2:,.3f} µm². Divided by",
        f"four: {def_per_lut_um2:,.3f} µm² -- the same {area_per_lut_um2:,.1f} µm²",
        "at this report's 0.1 µm² precision.",
        "",
        "## Cost per LUT4 (estimate)",
        "",
        "| quantity | value | source |",
        "|---|---|---|",
        f"| slot price | USD {PRICE_USD:,.0f} for {DIE_QUANTITY:,} dies |"
        f" {PRICE_SOURCE} ([wafer.space/price]({PRICE_URL})), retrieved {PRICE_DATE} |",
        f"| usable area per die | {SLOT_CORE_AREA_MM2} mm² inside the default pad ring | same listing |",
        "",
        "Arithmetic: USD"
        f" {PRICE_USD:,.0f} ÷ {DIE_QUANTITY:,} dies = USD {per_die_usd:.2f} per die;",
        f"USD {per_die_usd:.2f} ÷ {SLOT_CORE_AREA_MM2} mm² = USD"
        f" {price_per_mm2:.6f} per mm² of core; one LUT4 occupies"
        f" {area_per_lut_mm2:.7f} mm² of that core; {price_per_mm2:.6f} ×"
        f" {area_per_lut_mm2:.7f} = USD {cost_per_lut_usd:.8f}, reported as"
        f" **USD {cost_per_lut_usd:.5f} per LUT4 per die**. Using the DEF-derived",
        f"area instead of the record's rounded value lands on the same USD"
        f" {cost_per_lut_def_usd:.5f} at five decimal places.",
        "",
        "**This is an area-proportional shuttle estimate, and it assumes the",
        "whole slot core is available for tiles.** Whole-tile packing, chip-level",
        "logic and I/O, yield, testing and packaging all change the cost of a",
        "*usable* LUT, and the listed price is date-stamped and can change. No",
        "timing, power or yield claim is made or implied here.",
    ]
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(
        description="Render measurements/cost-per-lut.md from the committed record and routed DEF."
    )
    ap.add_argument(
        "--check", action="store_true",
        help="compare the committed file with a fresh render; exit non-zero if they differ",
    )
    args = ap.parse_args(argv)

    text = render()
    rel = OUT.relative_to(ROOT).as_posix()

    if args.check:
        if not OUT.is_file():
            print(f"ERROR: {rel} is missing; run measurements/cost_per_lut.py",
                  file=sys.stderr)
            return 1
        committed = OUT.read_text(encoding="utf-8")
        if committed != text:
            diff = difflib.unified_diff(
                committed.splitlines(keepends=True), text.splitlines(keepends=True),
                fromfile=f"{rel} (committed)", tofile=f"{rel} (fresh render)",
            )
            sys.stderr.writelines(diff)
            print(f"ERROR: {rel} has drifted from the record;"
                  " run measurements/cost_per_lut.py", file=sys.stderr)
            return 1
        print(f"{rel} is up to date")
        return 0

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
